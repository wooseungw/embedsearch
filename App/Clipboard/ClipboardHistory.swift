import Observation
import SearchCore

/// The last `capacity` copied texts, oldest first: a new text goes to the end and the front falls
/// off past `capacity` (FIFO). A text already there — copied again, or chosen from the history —
/// moves to the end instead of being added twice.
struct ClipboardQueue: Sendable {
    struct Entry: Sendable, Equatable {
        /// Stable while the entry lives, also across moves (a result keeps its selection).
        let id: Int
        let text: String
        /// What its row shows, worked out once here rather than on every keystroke: the first line
        /// with text (whitespace collapsed, up to 300 characters) and how many lines there are.
        let title: String
        let lineCount: Int
        /// UTF-8 of the `TextNormalizer` form of the text's start, which queries are matched
        /// against byte for byte (both sides normalized: the same as matching characters).
        let normalized: [UInt8]
        var copiedAt: Date
    }

    let capacity: Int
    private(set) var entries: [Entry] = []
    private var nextID = 1

    /// Matching looks this far into a text: enough for any query, and long copies stay cheap.
    static let matchedCharacters = 20_000

    init(capacity: Int) {
        precondition(capacity > 0)
        self.capacity = capacity
    }

    var newestFirst: [Entry] { entries.reversed() }

    mutating func add(_ text: String, at date: Date) {
        if let index = entries.firstIndex(where: { $0.text == text }) {
            var entry = entries.remove(at: index)
            entry.copiedAt = date
            entries.append(entry)
            return
        }
        var lineCount = 1
        for unit in text.utf8 where unit == 0x0A { lineCount += 1 }
        entries.append(Entry(id: nextID, text: text, title: Self.title(text), lineCount: lineCount,
                             normalized: Array(TextNormalizer.normalize(String(text.prefix(Self.matchedCharacters))).utf8),
                             copiedAt: date))
        nextID += 1
        if entries.count > capacity { entries.removeFirst(entries.count - capacity) }
    }

    /// Moves the entry to the end, as if it had just been copied; nil when it is gone.
    @discardableResult
    mutating func use(id: Int, at date: Date) -> Entry? {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return nil }
        var entry = entries.remove(at: index)
        entry.copiedAt = date
        entries.append(entry)
        return entry
    }

    mutating func remove(id: Int) {
        entries.removeAll { $0.id == id }
    }

    mutating func removeAll() {
        entries.removeAll()
    }

    /// The first line with text, whitespace collapsed, up to 300 characters.
    static func title(_ text: String) -> String {
        let line = text.split(whereSeparator: \.isNewline).first { $0.contains { !$0.isWhitespace } } ?? Substring(text)
        return String(line.split(whereSeparator: \.isWhitespace).joined(separator: " ").prefix(300))
    }

    /// `needle` occurs in `haystack` (bytes).
    static func contains(_ haystack: [UInt8], _ needle: [UInt8]) -> Bool {
        guard !needle.isEmpty else { return true }
        guard needle.count <= haystack.count else { return false }
        return haystack.withUnsafeBytes { h in
            needle.withUnsafeBytes { n in memmem(h.baseAddress, h.count, n.baseAddress, n.count) != nil }
        }
    }
}

/// Copied text, kept in memory only (never written to disk, never embedded): the pasteboard is
/// checked twice a second, since macOS sends no notification when it changes. Skipped: copies a
/// password manager marks as concealed or transient (nspasteboard.org), files copied in Finder (a
/// file's name is not text the user copied), whitespace, and texts over `maxCharacters`.
///
/// macOS 15.4+ can make reading the pasteboard ask the user (`NSPasteboard.accessBehavior`; off in
/// macOS 26 unless a developer default turns it on). Set to ask or deny, nothing is read: a read on
/// every copy would ask on every copy. `problem` says so.
@MainActor
@Observable
final class ClipboardHistory {
    nonisolated static let capacity = 30
    /// ~100k characters (a long article): a few hundred KB each in memory at most.
    nonisolated static let maxCharacters = 100_000
    nonisolated static let idPrefix = "clip:"
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]

    private(set) var queue = ClipboardQueue(capacity: ClipboardHistory.capacity)
    private(set) var isRunning = false
    /// macOS asks or denies when the pasteboard is read (see above).
    private(set) var isBlockedBySystem = false

    /// Why nothing is being recorded, if so.
    var problem: String? {
        if !isRunning { return "클립보드 기록이 꺼져 있습니다 — 설정 › 클립보드에서 켤 수 있습니다" }
        if isBlockedBySystem {
            return "macOS가 클립보드 읽기를 막고 있습니다 — 시스템 설정 › 개인정보 보호 및 보안에서 EmbedSearch의 붙여넣기를 허용하세요"
        }
        return nil
    }

    var count: Int { queue.entries.count }

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private var lastChangeCount = 0
    @ObservationIgnored private var timer: Timer?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    /// Starts recording (with what is on the pasteboard now) or stops and forgets everything.
    func setEnabled(_ enabled: Bool) {
        enabled ? start() : stop()
    }

    private func start() {
        guard !isRunning else { return }
        isRunning = true
        lastChangeCount = pasteboard.changeCount
        capture()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        // Lets the system batch this wakeup with others.
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
        isRunning = false
        queue.removeAll()
    }

    /// Records the pasteboard if it changed since the last look.
    func poll() {
        guard isRunning else { return }
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        capture()
    }

    private func capture() {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .ask, .alwaysDeny:
                isBlockedBySystem = true
                return
            default:
                isBlockedBySystem = false
            }
        }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.ignoredTypes.contains), !types.contains(.fileURL),
              let text = pasteboard.string(forType: .string) else { return }
        record(text)
    }

    func record(_ text: String, at date: Date = Date()) {
        // UTF-16 length: O(1) for the pasteboard's bridged strings, unlike `count`.
        guard text.utf16.count <= Self.maxCharacters, text.contains(where: { !$0.isWhitespace }) else { return }
        queue.add(text, at: date)
    }

    /// The result's entry was chosen (copied back): it becomes the newest.
    func use(itemID: String) {
        guard let id = Self.entryID(itemID) else { return }
        queue.use(id: id, at: Date())
    }

    func remove(itemID: String) {
        guard let id = Self.entryID(itemID) else { return }
        queue.remove(id: id)
    }

    func removeAll() {
        queue.removeAll()
    }

    static func entryID(_ itemID: String) -> Int? {
        guard itemID.hasPrefix(idPrefix) else { return nil }
        return Int(itemID.dropFirst(idPrefix.count))
    }

    /// Entries newest first: all of them for an empty query (fewer than `minimumQueryLength`
    /// characters: none), else those that have every content word of the query — any of its
    /// spellings, so "회의는" finds "회의" — ignoring case, width and punctuation.
    func results(matching query: String, limit: Int, minimumQueryLength: Int = 0, now: Date = Date()) -> [SearchResult] {
        let compact = TextNormalizer.compact(query)
        guard compact.count >= minimumQueryLength, limit > 0 else { return [] }
        let words = compact.isEmpty ? [] : QueryAnalyzer.analyze(query).contentTokens.map { $0.map { Array($0.utf8) } }
        var out: [SearchResult] = []
        for entry in queue.newestFirst
        where words.allSatisfy({ variants in variants.contains { ClipboardQueue.contains(entry.normalized, $0) } }) {
            out.append(SearchResult(item: Self.item(entry, now: now), score: 0, signals: [.lexical],
                                    breakdown: ScoreBreakdown()))
            if out.count >= limit { break }
        }
        return out
    }

    static func item(_ entry: ClipboardQueue.Entry, now: Date) -> SearchItem {
        SearchItem(id: "\(idPrefix)\(entry.id)", kind: .clipboard, title: entry.title,
                   subtitle: subtitle(entry, now: now), keywords: [], embeddingTitle: nil, embeddingText: "",
                   action: .copyText(entry.text), icon: .systemSymbol("doc.on.clipboard"))
    }

    /// "3분 전 · 12줄".
    static func subtitle(_ entry: ClipboardQueue.Entry, now: Date) -> String {
        let age = age(of: entry.copiedAt, now: now)
        return entry.lineCount > 1 ? "\(age) · \(entry.lineCount)줄" : age
    }

    static func age(of date: Date, now: Date) -> String {
        let seconds = max(0, Int(now.timeIntervalSince(date)))
        switch seconds {
        case ..<60: return "방금"
        case ..<3600: return "\(seconds / 60)분 전"
        case ..<86_400: return "\(seconds / 3600)시간 전"
        default: return "\(seconds / 86_400)일 전"
        }
    }
}

/// The panel's clipboard mode: the history, newest first, narrowed by what is typed.
struct ClipboardSearchService: SearchService {
    let history: ClipboardHistory

    func instantSearch(_ query: String, limit: Int) async -> [SearchResult] {
        await history.results(matching: query, limit: limit)
    }

    func fullSearch(_ query: String, limit: Int) async throws -> [SearchResult] {
        await instantSearch(query, limit: limit)
    }

    func recordSelection(itemID: String, query: String) async {
        await history.use(itemID: itemID)
    }

    func refresh() async {}

    func stateUpdates() async -> AsyncStream<EngineState> {
        AsyncStream { $0.finish() }
    }
}

/// The normal search with up to `clipboardLimit` clipboard entries that have the query's words
/// placed after its first `clipboardPosition` results, where the eye still is (the panel shows 8
/// rows of up to 50; their kind badge marks them). Choosing an entry touches only the history:
/// neither its text nor the query reaches the index's usage tables.
struct MergedSearchService: SearchService {
    let base: any SearchService
    let history: ClipboardHistory
    static let clipboardLimit = 3
    static let clipboardPosition = 3
    /// One letter matches nearly every copied text.
    static let minimumQueryLength = 2

    func instantSearch(_ query: String, limit: Int) async -> [SearchResult] {
        Self.merge(await base.instantSearch(query, limit: limit), await clipboard(query))
    }

    func fullSearch(_ query: String, limit: Int) async throws -> [SearchResult] {
        Self.merge(try await base.fullSearch(query, limit: limit), await clipboard(query))
    }

    /// `clips` after the first `clipboardPosition` main results (fewer: after all of them, before a
    /// trailing settings section).
    static func merge(_ found: [SearchResult], _ clips: [SearchResult]) -> [SearchResult] {
        guard !clips.isEmpty else { return found }
        let mainCount = found.firstIndex { $0.section != .main } ?? found.count
        var merged = found
        merged.insert(contentsOf: clips, at: min(clipboardPosition, mainCount))
        return merged
    }

    private func clipboard(_ query: String) async -> [SearchResult] {
        await history.results(matching: query, limit: Self.clipboardLimit, minimumQueryLength: Self.minimumQueryLength)
    }

    func recordSelection(itemID: String, query: String) async {
        if itemID.hasPrefix(ClipboardHistory.idPrefix) {
            await history.use(itemID: itemID)
        } else {
            await base.recordSelection(itemID: itemID, query: query)
        }
    }

    func refresh() async { await base.refresh() }

    func stateUpdates() async -> AsyncStream<EngineState> { await base.stateUpdates() }
}
